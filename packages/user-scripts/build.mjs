#!/usr/bin/env node
// 用户脚本构建（builtin 与 samples 共用这一个脚本）：builtin 的形态为什么是 IIFE 单文件，
// 见 docs/adr/0008-builtin-scripts-iife-build.md。
//
//   · src/builtin/  内置注入件 → dist/builtin/ 下的 IIFE 文件（chrome.userScripts 以
//     `{ file }` 注册，件必须自包含、无 import/export 残留）
//   · src/builtin/relay/  中继件 → 不产文件，打成 IIFE 后在同目录生成 relay-code.gen.ts
//     （RELAY_IIFE 字符串常量，不入库，每次从源码重新生成）—— SW 侧以 `{ code }` 两段式注册，
//     经 `@duoling/user-scripts/builtin/relay-code.gen` 消费
//   · src/samples/  用户脚本样例 → dist/samples/<名>/<名>.user.js 单文件（esbuild 会剥
//     注释，metadata 头由各样例的 meta.json 生成 banner）；src/samples/raw/ 的坏源码样本
//     不参与构建（编不过是特性），原样拷进 dist/samples
//
// 用法：
//   node build.mjs            构建一次（扩展的 build / dev 前置步骤，pnpm -r build 收口）
//   node build.mjs --watch    监听重建（内置件与样例一起挂 watch）
//
// 产物落在包内 dist/{builtin,samples}/：builtin 那份由 wxt.config.ts 的 build:publicAssets
// 钩子取进扩展产物；samples 那份由 scripts/pack-uscripts.mts 打 zip 分发。
// dist 不入库（.gitignore）：源码是真相源，产物随构建重建，防 drift。
//
// 本文件同时是**构建入口表的真相源**（registry.test.ts 比对注册面与入口表）——它被测试
// import 时靠底部的 main 守卫不触发构建。
import { build, context } from 'esbuild'
import {
  cpSync,
  existsSync,
  readFileSync,
  readdirSync,
  rmSync,
  statSync,
  writeFileSync,
} from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const BUILTIN_OUT = resolve(here, 'dist/builtin')
const SAMPLES_OUT = resolve(here, 'dist/samples')

/** 内置注入件入口表：键 = 产物文件名（不含扩展名）。键名带 `duoling-` 前缀的理由：产物
 * 落在扩展产物根，与扩展自身的产物同目录，前缀避免重名（与 icons / help 那类资产并列）。
 * `{ file }` 的字面量在 src/builtin/registry.ts 里声明，两边改名必须同步。 */
export const BUILTIN_ENTRY_POINTS = {
  'duoling-recorder': resolve(here, 'src/builtin/recorder/entry.ts'),
  'duoling-page-inspector': resolve(here, 'src/builtin/inspector/entry.ts'),
  'duoling-float-host': resolve(here, 'src/builtin/float-host/entry.ts'),
}

/** 样例入口表：键 = 样例目录名（产物 dist/samples/<键>/<键>.user.js）。元数据取入口同目录
 * 的 meta.json；键改名时 raw 目录、e2e / coverage 的路径引用一并同步。 */
const SAMPLE_ENTRIES = {
  'omni-probe': 'src/samples/omni-probe/main.ts',
  'run-log-demo': 'src/samples/run-log-demo/main.ts',
}

/** 不参与构建的坏源码样本（src/samples/raw/<名>/，编不过是特性），原样拷进 dist/samples */
const RAW_DIRS = ['syntax-error', 'runtime-error']

/** esbuild 选项基座（builtin 与 samples 同档）：IIFE 单文件，产物自包含 */
const baseOptions = {
  bundle: true,
  format: 'iife',
  platform: 'browser',
  // 与 manifest 的 minimum_chrome_version 同一档（自定义 USER_SCRIPT 世界需内核 133+，本项目取 135）
  target: 'chrome135',
  // 件要注入第三方页面并被调试：保持可读，不做压缩；devtools 里看到的就是源码形状
  minify: false,
  sourcemap: false,
  // 件里有中文诊断信息（console.warn）：按 utf8 输出，别转成 \uXXXX
  charset: 'utf8',
  legalComments: 'none',
}

const builtinOptions = {
  ...baseOptions,
  entryPoints: BUILTIN_ENTRY_POINTS,
  outdir: BUILTIN_OUT,
  // 不开 splitting：iife 不支持代码分割（esbuild 只在 esm 下才允许）。副作用是共享的
  // 协议代码会被复制进引用它的每个件 —— userScripts 按世界注入，件之间无法共享模块实例。
}

// 中继件装配是两段式（装配段由 SW 侧生成，见 SW 包 relay/sync.ts 的 buildRelayInit）：①本件把安装函数挂到
// window，②装配段把运行期密钥递进去。密钥进不了代码串，故件以字符串内嵌而非 { file } 注册
// —— 产物不落 dist，改写为 gen 模块（RELAY_IIFE 常量），由 SW 经 exports 子路径消费。
const RELAY_ENTRY = resolve(here, 'src/builtin/relay/entry.ts')
const RELAY_GEN = resolve(here, 'src/builtin/relay/relay-code.gen.ts')

const relayGenPlugin = {
  name: 'relay-gen',
  setup(builder) {
    builder.onEnd((result) => {
      if (result.errors.length) return
      const code = result.outputFiles[0].text
      writeFileSync(
        RELAY_GEN,
        `// AUTO-GENERATED by build.mjs（源码：src/builtin/relay/entry.ts + install.ts）—— 不要手改；\n` +
          `// 本文件不入库（根 .gitignore），每次 build 从源码重新生成，源码与生成物之间无 drift 存活空间。\n` +
          `/** 中继件 IIFE 产物（自包含，无 import/export 残留；随 SW 以 { code } 注册注入） */\n` +
          `export const RELAY_IIFE = ${JSON.stringify(code)}\n`,
      )
      console.log(
        `[user-scripts] 中继件 IIFE 已生成 → ${RELAY_GEN.slice(here.length + 1)}（${code.length} 字节）`,
      )
    })
  },
}

const relayOptions = {
  ...baseOptions,
  entryPoints: [RELAY_ENTRY],
  write: false,
  plugins: [relayGenPlugin],
}

/** meta.json → `// ==UserScript==` 块文本。键序即行序（JSON 对象序保留），空值渲染成裸 `@key` */
function renderMeta(meta) {
  const lines = ['// ==UserScript==']
  for (const [key, value] of Object.entries(meta)) {
    for (const v of Array.isArray(value) ? value : [value]) {
      lines.push(v ? `// @${key} ${v}` : `// @${key}`)
    }
  }
  lines.push('// ==/UserScript==')
  return lines.join('\n')
}

function sampleOptions(name, entry) {
  const metaPath = resolve(here, dirname(entry), 'meta.json')
  const banner = renderMeta(JSON.parse(readFileSync(metaPath, 'utf8')))
  const outfile = join(SAMPLES_OUT, name, `${name}.user.js`)
  // 严格性：原 .user.js 在 IIFE 里显式 'use strict'；ESM 源码本身就是严格语义，esbuild 的
  // iife 包裹不再回填指令 —— 样例源码不含 this/with/未声明赋值这类两种模式的差异点，行为一致。
  return { ...baseOptions, entryPoints: [resolve(here, entry)], outfile, banner: { js: banner } }
}

async function buildOnce() {
  // 中继件 gen 排最前：SW 侧测试 / 类型检查都吃它，先于其余产物落位
  await build(relayOptions)
  rmSync(BUILTIN_OUT, { recursive: true, force: true })
  rmSync(SAMPLES_OUT, { recursive: true, force: true })

  const builtinResult = await build(builtinOptions)
  if (builtinResult.warnings.length) {
    for (const w of builtinResult.warnings) console.warn('[user-scripts] 内置件警告：', w.text)
  }
  console.log(
    `[user-scripts] 已构建 ${Object.keys(BUILTIN_ENTRY_POINTS).length} 个内置件 → ${BUILTIN_OUT.slice(here.length + 1)}`,
  )

  for (const [name, entry] of Object.entries(SAMPLE_ENTRIES)) {
    const opts = sampleOptions(name, entry)
    await build(opts)
    const out = readFileSync(opts.outfile, 'utf8')
    if (!out.startsWith('// ==UserScript=='))
      throw new Error(`${name}：产物缺元数据头（banner 未生效？）`)
    console.log(
      `[user-scripts] ${name} → ${opts.outfile.slice(here.length + 1)}（${out.length} 字节）`,
    )
  }
  for (const name of RAW_DIRS) {
    const src = resolve(here, 'src/samples/raw', name)
    if (!existsSync(src)) throw new Error(`raw 样本缺失：${src}`)
    cpSync(src, join(SAMPLES_OUT, name), { recursive: true })
  }
  const dirs = readdirSync(SAMPLES_OUT).filter((d) => statSync(join(SAMPLES_OUT, d)).isDirectory())
  console.log(
    `[user-scripts] 样例完成：${Object.keys(SAMPLE_ENTRIES).length} 个样例 + ${RAW_DIRS.length} 个 raw 样本 → ${SAMPLES_OUT.slice(here.length + 1)}（${dirs.length} 目录）`,
  )
}

async function watchAll() {
  const contexts = [
    await context(relayOptions),
    await context(builtinOptions),
    ...Object.entries(SAMPLE_ENTRIES).map(([name, entry]) => context(sampleOptions(name, entry))),
  ]
  for (const ctx of await Promise.all(contexts)) await ctx.watch()
  console.log(`[user-scripts] 监听中（Ctrl+C 退出）→ 中继件 gen 与 dist/{builtin,samples}`)
}

// main 守卫：被 registry.test.ts 等 import 时只取入口表、不触发构建
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  process.argv.includes('--watch') ? await watchAll() : await buildOnce()
}
