#!/usr/bin/env node
// 中继件的包内构建：src/relay/entry.ts（IIFE bundle）→ 生成同目录的 relay-code.gen.ts。
//
// 为什么生成 .ts 而不是 dist 产物文件：中继件不再以「公共资产文件 + { file } 注册」分发，
// 而是**字符串内嵌**进包产物（js: [{ code: RELAY_IIFE }, { code: buildRelayInit(secret) }]）
// —— 第三方 npm install 完即全量，不碰资产拷贝。生成 .ts（而非 ?raw 导入）让 typecheck
// 与 dts 生成把它当普通模块，无构建顺序耦合面。
//
// gen 文件**不入库**（见根 .gitignore）：build 与 test 脚本都前置本脚本，每次从 relay 源码
// 重新生成 —— 源码与生成物之间不存在 drift 的存活空间。
import { build } from 'esbuild'
import { writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const OUT = resolve(here, 'src/relay/relay-code.gen.ts')

const result = await build({
  entryPoints: [resolve(here, 'src/relay/entry.ts')],
  bundle: true,
  format: 'iife',
  platform: 'browser',
  // 与 manifest 的 minimum_chrome_version 同一档（自定义 USER_SCRIPT 世界需内核 133+）
  target: 'chrome135',
  // 件要注入第三方页面并被调试：保持可读（与 builtin-scripts 其余件同一取向）
  minify: false,
  sourcemap: false,
  // 件里有中文诊断信息（console.warn）：按 utf8 输出，别转成 \uXXXX
  charset: 'utf8',
  legalComments: 'none',
  write: false,
})

const code = result.outputFiles[0].text
writeFileSync(
  OUT,
  `// AUTO-GENERATED by build-relay.mjs（源码：relay/entry.ts + relay/install.ts）—— 不要手改；\n` +
    `// 本文件不入库，build / test 脚本前置的 build-relay.mjs 每次从源码重新生成。\n` +
    `/** 中继件 IIFE 产物（自包含，无 import/export 残留；chrome.userScripts.js[].code 直接可注入） */\n` +
    `export const RELAY_IIFE = ${JSON.stringify(code)}\n`,
)
console.log(`[userscript-runtime] 中继件 IIFE 已生成 → ${OUT}（${code.length} 字节）`)
